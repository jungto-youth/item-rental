-- 0015 — 소속을 3단(지부 · 지회 · 모둠)으로 통일한다.
--
-- 0014 이전 값은 "서울 · 동부"처럼 지회·모둠 2단이었다. 당시 회원은 모두
-- 청년지부였으므로 표준 조합에만 "청년지부 · " 접두어를 붙인다.
-- NULL·해석할 수 없는 값·과거 스냅샷은 건드리지 않는다.
-- 재실행해도 이미 3단인 값은 IN 목록에 없으므로 안전하다.

UPDATE members
   SET affiliation = '청년지부 · ' || affiliation
 WHERE affiliation IN (
   '서울 · 동부', '서울 · 서부', '서울 · 남부', '서울 · 북부',
   '경기 · 동부', '경기 · 서부', '경기 · 남부', '경기 · 북부',
   '남부 · 충청', '남부 · 대전/광주', '남부 · 대구/경북', '남부 · 부산/경남'
 );

UPDATE reservations
   SET member_affiliation_snapshot = '청년지부 · ' || member_affiliation_snapshot
 WHERE member_affiliation_snapshot IN (
   '서울 · 동부', '서울 · 서부', '서울 · 남부', '서울 · 북부',
   '경기 · 동부', '경기 · 서부', '경기 · 남부', '경기 · 북부',
   '남부 · 충청', '남부 · 대전/광주', '남부 · 대구/경북', '남부 · 부산/경남'
 );
